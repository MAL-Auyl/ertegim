#!/usr/bin/env node
// Writes public/offline-manifest.json — what «Скачать для офлайна» downloads
// and what the service worker keeps (see public/offline.js).
//
//   node tools/offline-manifest.js        (or: bun tools/offline-manifest.js)
//
// Re-run after adding or changing anything in public/audio or public/images;
// tests/offline.test.js fails until the manifest matches the files.
//
//   shell — every page and script in public/ root + icons (no hashes: the
//           worker fetches these network-first anyway);
//   media — every lesson/story audio line, plus the pictures and fox clips
//           that some page actually references (sha1 prefix + size each).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..", "public");
const SHELL_EXCLUDE = new Set(["sw.js", "voices.html", "offline-manifest.json"]);
const TEXT_EXT = /\.(js|html|css|webmanifest)$/;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walk(p) : [p];
  });
}

const url = (p) => "/" + path.relative(ROOT, p).split(path.sep).join("/");

function buildManifest(root = ROOT) {
  const top = fs.readdirSync(root, { withFileTypes: true }).filter((d) => d.isFile()).map((d) => d.name);
  const shell = ["/", ...top.filter((n) => TEXT_EXT.test(n) && !SHELL_EXCLUDE.has(n)).map((n) => "/" + n)];
  shell.push("/favicon.ico", ...fs.readdirSync(path.join(root, "icons")).map((n) => "/icons/" + n));

  // Text the pages ship: a picture is offline-worthy only if it is named here.
  const text = top.filter((n) => TEXT_EXT.test(n)).map((n) => fs.readFileSync(path.join(root, n), "utf8")).join("\n");
  const audio = walk(path.join(root, "audio")).filter((p) => p.endsWith(".wav"));
  const images = walk(path.join(root, "images")).filter((p) => text.includes(url(p)));

  const media = [...audio, ...images].sort().map((p) => {
    const buf = fs.readFileSync(p);
    return { url: url(p), bytes: buf.length, hash: crypto.createHash("sha1").update(buf).digest("hex").slice(0, 12) };
  });
  return { note: "generated by tools/offline-manifest.js — do not edit", shell: shell.sort(), media };
}

if (require.main === module) {
  const m = buildManifest();
  fs.writeFileSync(path.join(ROOT, "offline-manifest.json"), JSON.stringify(m, null, 1) + "\n");
  const mb = (m.media.reduce((a, f) => a + f.bytes, 0) / 1048576).toFixed(1);
  console.log(`offline-manifest.json: ${m.shell.length} shell files, ${m.media.length} media files, ${mb} MB`);
}

module.exports = { buildManifest };
